import { describe, expect, it } from "vitest";
import { TFile, TFolder } from "obsidian";
import { writePipelineOutput } from "../../src/pipeline/writer";
import type { OutputWord } from "../../src/pipeline/output";

class FakeVault {
  files = new Map<string, string>();
  folders = new Set<string>();
  adapter = {
    getBasePath: () => "/vault",
    getResourcePath: (path: string) => `app://local/${path}`,
    exists: async (path: string) => this.folders.has(path) || this.files.has(path),
    read: async (path: string) => {
      if (!this.files.has(path)) throw new Error("not found");
      return this.files.get(path)!;
    },
  };

  getAbstractFileByPath(path: string): TFile | TFolder | null {
    if (this.files.has(path)) {
      const file = new (TFile as any)(path) as TFile;
      file.stat.size = this.files.get(path)!.length;
      return file;
    }
    if (this.folders.has(path)) return new (TFolder as any)(path);
    return null;
  }

  async createFolder(path: string): Promise<void> {
    this.folders.add(path);
  }

  async create(path: string, content: string): Promise<TFile> {
    this.files.set(path, content);
    return this.getAbstractFileByPath(path) as TFile;
  }

  async modify(file: TFile, content: string): Promise<void> {
    this.files.set(file.path, content);
  }

  async cachedRead(file: TFile): Promise<string> {
    return this.files.get(file.path) ?? "";
  }
}

function word(overrides: Partial<OutputWord> = {}): OutputWord {
  return {
    word: "kata",
    form: "kade",
    sourcePath: "Words/Proto/kata.md",
    meta: {},
    history: [{ label: "Lenition", form: "kade" }],
    ...overrides,
  };
}

function options(vault: FakeVault, step: any, words: OutputWord[] = [word()]) {
  return {
    app: { vault } as any,
    step: {
      id: "out",
      kind: "output" as const,
      label: "Output",
      path: "Words/Modern",
      format: "markdown" as const,
      field: "word",
      overwrite: true,
      ...step,
    },
    words,
    changes: ["Changes/Demo.lsc"],
    pipelinePath: "Pipelines/Demo.canvas",
  };
}

describe("pipeline writer", () => {
  it("writes only the useful properties", async () => {
    const vault = new FakeVault();
    const result = await writePipelineOutput(options(vault, {}));
    expect(result.errors).toEqual([]);
    expect(result.paths).toEqual(["Words/Modern/kade.md"]);
    const content = vault.files.get("Words/Modern/kade.md")!;
    expect(content).toContain('source: "[[Words/Proto/kata]]"');
    expect(content).toContain('original: "kata"');
    expect(content).toContain('word: "kade"');
    expect(content).toContain('pipeline: "Modern"');
    expect(content).not.toContain("| Stage |");
    expect(content).not.toContain("langscape: word");
    expect(content).not.toContain("Generated by");
    expect(vault.folders.has("Words/Modern")).toBe(true);
  });

  it("uses an explicit pipeline name and evolved-word property", async () => {
    const vault = new FakeVault();
    const result = await writePipelineOutput(
      options(vault, { name: "Modern Language", field: "lexeme" })
    );
    expect(result.paths).toEqual(["Words/Modern/kade.md"]);
    const content = vault.files.get("Words/Modern/kade.md")!;
    expect(content).toContain('pipeline: "Modern Language"');
    expect(content).toContain('lexeme: "kade"');
    expect(content).not.toContain('word: "kade"');
  });

  it("does not overwrite human notes", async () => {
    const vault = new FakeVault();
    vault.files.set("Words/Modern/kade.md", "---\nword: human\n---\nDo not touch");
    const result = await writePipelineOutput(options(vault, {}));
    expect(result.paths).toEqual(["Words/Modern/kade-2.md"]);
    expect(vault.files.get("Words/Modern/kade.md")).toContain("Do not touch");
  });

  it("refreshes notes it generated", async () => {
    const vault = new FakeVault();
    vault.files.set(
      "Words/Modern/kade.md",
      '---\npipeline: "Modern"\noriginal: "kata"\nword: "old"\n---\n'
    );
    const result = await writePipelineOutput(options(vault, {}));
    expect(result.paths).toEqual(["Words/Modern/kade.md"]);
    expect(vault.files.get("Words/Modern/kade.md")).toContain('word: "kade"');
  });

  it("suffixes instead of overwriting when overwrite is disabled", async () => {
    const vault = new FakeVault();
    vault.files.set(
      "Words/Modern/kade.md",
      '---\npipeline: "Modern"\noriginal: "kata"\nword: "old"\n---\n'
    );
    const result = await writePipelineOutput(options(vault, { overwrite: false }));
    expect(result.paths).toEqual(["Words/Modern/kade-2.md"]);
    expect(vault.files.get("Words/Modern/kade.md")).toContain('"old"');
  });

  it("never writes over its source note", async () => {
    const vault = new FakeVault();
    vault.files.set("Words/Modern/kade.md", "---\nword: human\n---\n");
    const result = await writePipelineOutput(
      options(vault, {}, [word({ sourcePath: "Words/Modern/kade.md", form: "kade" })])
    );
    expect(result.paths[0]).toBe("Words/Modern/kade-2.md");
  });

  it("writes .wli output files", async () => {
    const vault = new FakeVault();
    const result = await writePipelineOutput(
      options(vault, { path: "Build/evolved.wli", format: "wli" }, [
        word({ form: "kade" }),
        word({ form: "eke" }),
      ])
    );
    expect(result.paths).toEqual(["Build/evolved.wli"]);
    expect(vault.files.get("Build/evolved.wli")).toBe("kade\neke\n");
  });

  it("turns an empty word list into an error", async () => {
    const vault = new FakeVault();
    const result = await writePipelineOutput(options(vault, {}, []));
    expect(result.errors[0]).toMatch(/no words/i);
  });

  it("handles filename templates", async () => {
    const vault = new FakeVault();
    const result = await writePipelineOutput(
      options(vault, { filename: "{index}-{word}" })
    );
    expect(result.paths).toEqual(["Words/Modern/1-kade.md"]);
  });
});

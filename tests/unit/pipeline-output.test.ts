import { describe, expect, it } from "vitest";
import {
  defaultPipelineName,
  expandFilenameTemplate,
  isGeneratedNote,
  renderMarkdownNote,
  renderWli,
  sanitizeFilename,
  type OutputWord,
} from "../../src/pipeline/output";

const word: OutputWord = {
  word: "kata",
  form: "kade",
  sourcePath: "Words/Proto/kata.md",
  meta: { gloss: "stone" },
  history: [
    { label: "Lenition", form: "kada" },
    { label: "Final-Devoicing", form: "kade" },
  ],
};

describe("pipeline output rendering", () => {
  it("renders only the source, original, evolved word, and pipeline", () => {
    const note = renderMarkdownNote(word, { pipelineName: "Modern" });
    expect(note).toBe(
      [
        "---",
        'source: "[[Words/Proto/kata]]"',
        'original: "kata"',
        'word: "kade"',
        'pipeline: "Modern"',
        "---",
        "",
      ].join("\n")
    );
    expect(note).not.toContain("# kade");
    expect(note).not.toContain("| Stage |");
    expect(note).not.toContain("Sound changes");
    expect(note).not.toContain("Generated by");
  });

  it("supports a custom evolved-word property", () => {
    const note = renderMarkdownNote(word, {
      pipelineName: "Modern",
      outputField: "lexeme",
    });
    expect(note).toContain('lexeme: "kade"');
    expect(note).not.toContain('word: "kade"');
    expect(note).not.toContain("langscape:");
  });

  it("does not let a custom property overwrite provenance keys", () => {
    for (const reserved of ["source", "original", "pipeline"]) {
      const note = renderMarkdownNote(word, {
        pipelineName: "Modern",
        outputField: reserved,
      });
      expect(note).toContain(`${reserved}: "Modern"`.replace("Modern", reserved === "source" ? "[[Words/Proto/kata]]" : reserved === "original" ? "kata" : "Modern"));
      expect(note).toContain('word: "kade"');
    }
  });

  it("omits source for inline words", () => {
    const note = renderMarkdownNote({ ...word, sourcePath: undefined }, { pipelineName: "Modern" });
    expect(note).not.toContain("source:");
    expect(note).toContain('original: "kata"');
  });

  it("identifies generated and human notes", () => {
    const note = renderMarkdownNote(word, { pipelineName: "Modern" });
    expect(isGeneratedNote(note)).toBe(true);
    expect(
      isGeneratedNote("---\npipeline: Modern\noriginal: kata\nword: kade\n---\n")
    ).toBe(true);
    expect(
      isGeneratedNote("---\nlangscape: word\nword: old\n---\n")
    ).toBe(true);
    expect(isGeneratedNote("---\nword: human\n---\n")).toBe(false);
    expect(isGeneratedNote("# just a note")).toBe(false);
  });

  it("renders word lists", () => {
    expect(renderWli([word, { ...word, form: "eke" }])).toBe("kade\neke\n");
    expect(renderWli([])).toBe("");
  });

  it("sanitizes conlang filenames without stripping diacritics", () => {
    expect(sanitizeFilename("Þing/vellir: 2026")).toBe("Þing-vellir- 2026");
    expect(sanitizeFilename("a|b*c?")).toBe("a-b-c");
    expect(sanitizeFilename("...")).toBe("word");
    expect(sanitizeFilename("CON")).toBe("word-CON");
    expect(sanitizeFilename("kata\nkatu")).toBe("kata katu");
  });

  it("expands filename templates", () => {
    expect(expandFilenameTemplate("{index}-{word}", word, 2)).toBe("3-kade");
    expect(expandFilenameTemplate("{proto}-{source}", word, 0)).toBe("kata-kata");
    expect(expandFilenameTemplate(undefined, word, 0)).toBe("kade");
  });

  it("derives the pipeline name from the output folder", () => {
    expect(defaultPipelineName("Languages/Modern")).toBe("Modern");
    expect(defaultPipelineName("Languages/Modern/")).toBe("Modern");
    expect(defaultPipelineName("Build/evolved.wli")).toBe("evolved");
    expect(defaultPipelineName("")).toBe("output");
  });
});
